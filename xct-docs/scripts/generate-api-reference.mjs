#!/usr/bin/env node
/**
 * Generate xct-docs/docs/api-reference/openapi-public.md from the live
 * proxy's /openapi-public.json.
 *
 * Usage:
 *   PROXY_URL=https://api.xct.test node scripts/generate-api-reference.mjs
 *
 * Or read a local file:
 *   OPENAPI_FILE=/tmp/openapi-public.json node scripts/generate-api-reference.mjs
 *
 * No external deps — Node 18+ stdlib only.
 */

import { writeFileSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "..", "docs", "api-reference", "openapi-public.md");

const PROXY_URL = process.env.PROXY_URL ?? "http://127.0.0.1:4000";
const OPENAPI_FILE = process.env.OPENAPI_FILE;

const FRONT_MATTER = `---
sidebar_position: 2
title: "openapi-public.json (auto-generated)"
---

# \`/openapi-public.json\` — auto-generated reference

> Generated by \`xct-docs/scripts/generate-api-reference.mjs\` on \
${new Date().toISOString()}. **Do not edit by hand.**

`;

async function loadSpec() {
  if (OPENAPI_FILE) {
    return JSON.parse(readFileSync(OPENAPI_FILE, "utf-8"));
  }
  const resp = await fetch(`${PROXY_URL}/openapi-public.json`);
  if (!resp.ok) throw new Error(`Fetch failed: HTTP ${resp.status}`);
  return await resp.json();
}

function renderMethod(path, method, op) {
  const lines = [];
  lines.push(`\n## \`${method.toUpperCase()} ${path}\``);
  if (op.summary) lines.push(`\n${op.summary}`);
  if (op.description) lines.push(`\n${op.description}`);

  // Parameters
  const params = op.parameters ?? [];
  if (params.length) {
    lines.push("\n### Parameters\n");
    lines.push("| Name | In | Required | Type | Description |");
    lines.push("|---|---|---|---|---|");
    for (const p of params) {
      const t = p.schema?.type ?? "—";
      const req = p.required ? "yes" : "no";
      lines.push(`| \`${p.name}\` | ${p.in} | ${req} | ${t} | ${p.description ?? ""} |`);
    }
  }

  // Request body
  if (op.requestBody?.content) {
    lines.push("\n### Request body\n");
    for (const [ct, media] of Object.entries(op.requestBody.content)) {
      lines.push(`Content-Type: \`${ct}\`\n`);
      if (media.schema) {
        lines.push("```json");
        lines.push(JSON.stringify(media.schema, null, 2).slice(0, 4000));
        lines.push("```");
      }
    }
  }

  // Responses
  if (op.responses) {
    lines.push("\n### Responses\n");
    for (const [code, resp] of Object.entries(op.responses)) {
      lines.push(`**${code}** — ${resp.description ?? ""}`);
      if (resp.content) {
        for (const [ct, media] of Object.entries(resp.content)) {
          if (media.schema) {
            lines.push(`\n\`${ct}\`:\n`);
            lines.push("```json");
            lines.push(JSON.stringify(media.schema, null, 2).slice(0, 2000));
            lines.push("```");
          }
        }
      }
    }
  }

  return lines.join("\n");
}

function render(spec) {
  const out = [FRONT_MATTER];
  const paths = Object.entries(spec.paths ?? {}).sort();
  for (const [path, ops] of paths) {
    for (const method of ["get", "post", "patch", "put", "delete"]) {
      if (ops[method]) out.push(renderMethod(path, method, ops[method]));
    }
  }

  const schemas = spec.components?.schemas ?? {};
  if (Object.keys(schemas).length) {
    out.push("\n## Schemas\n");
    for (const [name, schema] of Object.entries(schemas).sort()) {
      out.push(`\n### \`${name}\`\n`);
      out.push("```json");
      out.push(JSON.stringify(schema, null, 2).slice(0, 3000));
      out.push("```");
    }
  }

  return out.join("\n");
}

const spec = await loadSpec();
writeFileSync(OUT, render(spec));
console.log(`Wrote ${OUT} from ${spec.info?.title} (${Object.keys(spec.paths ?? {}).length} paths).`);
