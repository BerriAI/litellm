export const gardenCardName = (card: GuardrailCardInfo, t: TFunction): string =>
  card.nameKey ? t(card.nameKey) : card.name;

export const gardenCardDescription = (card: GuardrailCardInfo, t: TFunction): string =>
  card.descriptionKey ? t(card.descriptionKey) : card.description;

