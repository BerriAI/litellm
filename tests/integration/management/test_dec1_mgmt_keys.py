        assert second["current_page"] == 2
        hashes: Final = [*list_value(first["keys"]), *list_value(second["keys"])]
        assert all(isinstance(value, str) for value in hashes)
        assert sorted(hashes) == sorted(digest(key) for key in keys)  # pyright: ignore[reportArgumentType]  # strings checked above


