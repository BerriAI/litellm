def test_regenerate_with_a_grace_period_sets_revoke_at_that_far_ahead(gateway: Gateway) -> None:
    """grace_period "2h" writes a deprecated row whose active_token_id is the new key's hash and whose revoke_at is
    about two hours from now (between 7000 and 7300 seconds ahead), and the old key keeps authenticating."""
    with gateway.scenario() as scenario:
        old: Final = _uncleaned_key(gateway)
        old_hash: Final = digest(old)
        new: Final = string_value(gateway.post("/key/regenerate", {"key": old, "grace_period": "2h"})["key"])
        scenario.cleanups.callback(
            write_rows, 'DELETE FROM "LiteLLM_DeprecatedVerificationToken" WHERE token = %s', (old_hash,)
        )
        scenario.cleanups.callback(scenario.delete_key, new)
        rows: Final = deprecated_key_rows(old_hash)
        assert len(rows) == 1
        assert rows[0]["active_token_id"] == digest(new)
        assert 7000 < _revoke_in_seconds(old_hash) < 7300
        assert get(gateway, "/key/info", key=old).status_code == 200


