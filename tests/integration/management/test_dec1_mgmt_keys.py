def test_key_list_return_full_object_answers_key_objects(gateway: Gateway) -> None:
    """With return_full_object=true each entry is an object carrying token and key_alias instead of a bare hash."""
    with gateway.scenario() as scenario:
        team_id: Final = scenario.team()
        alias: Final = unique("full")
        key: Final = scenario.key(team_id=team_id, key_alias=alias)
        listed: Final = gateway.get("/key/list", {"team_id": team_id, "return_full_object": "true"})
        entries: Final = [object_value(entry) for entry in list_value(listed["keys"])]
        assert [(entry["token"], entry["key_alias"]) for entry in entries] == [(digest(key), alias)]


def test_key_list_for_an_internal_user_without_filters_lists_only_their_keys(gateway: Gateway) -> None:
    """An internal user calling /key/list with no filters sees only keys whose user_id is theirs: their own key's
    hash is listed and another user's key is not. UNVERIFIED: the exact non admin default scope is in
    `validate_key_list_check` and `_list_key_helper`."""
    with gateway.scenario() as scenario:
        user: Final = caller(scenario, "internal_user")
        stranger: Final = caller(scenario, "internal_user")
        listed: Final = get(gateway, "/key/list", key=user.key)
        assert listed.status_code == 200, listed.text
        hashes: Final = list_value(body_of(listed)["keys"])
        assert digest(user.key) in hashes
        assert digest(stranger.key) not in hashes


def test_key_block_with_a_malformed_key_is_400_invalid_key_format(gateway: Gateway) -> None:
    """/key/block validates the key's shape before any lookup: a value that is neither sk- plus url safe
    characters nor a 64 character hex hash answers 400 with message "Invalid key format." and param key."""
    response: Final = post(gateway, "/key/block", {"key": "not a key!"})
    assert response.status_code == 400, response.text
    error: Final = proxy_error(response)
    assert error["message"] == "Invalid key format."
    assert error["param"] == "key"


def test_key_block_by_hash_returns_the_updated_row_and_unblock_restores_it(gateway: Gateway) -> None:
    """Blocking a key by its hash answers 200 with the updated row (token equal to the hash, blocked true) and the
    row is blocked; /key/unblock with the raw key flips it back to false."""
    with gateway.scenario() as scenario:
        key: Final = scenario.key()
        blocked: Final = post(gateway, "/key/block", {"key": digest(key)})
        assert blocked.status_code == 200, blocked.text
        assert body_of(blocked)["token"] == digest(key)
        assert body_of(blocked)["blocked"] is True
        assert key_rows(key)[0]["blocked"] is True
        unblocked: Final = post(gateway, "/key/unblock", {"key": key})
        assert unblocked.status_code == 200, unblocked.text
        assert key_rows(key)[0]["blocked"] is False
