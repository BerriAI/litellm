def _uncleaned_key(gateway: Gateway, **fields: JsonValue) -> str:
    """A key with no scenario cleanup, for tests that rotate or delete it themselves."""
    return string_value(gateway.post("/key/generate", fields)["key"])


def _revoke_in_seconds(old_hash: str) -> float:
    rows: Final = read_rows(
        'SELECT EXTRACT(EPOCH FROM revoke_at - now())::float AS seconds FROM "LiteLLM_DeprecatedVerificationToken" '
        "WHERE token = %s",
        (old_hash,),
    )
    assert len(rows) == 1, rows
    seconds: Final = rows[0]["seconds"]
    assert isinstance(seconds, float)
    return seconds


