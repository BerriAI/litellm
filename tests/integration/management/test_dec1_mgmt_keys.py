_STATE_SQL: Final = {
    "blocked": 'UPDATE "LiteLLM_VerificationToken" SET blocked = true WHERE token = %s',
    "expired": "UPDATE \"LiteLLM_VerificationToken\" SET expires = now() - interval '1 hour' WHERE token = %s",
    "blocked_and_expired": (
        "UPDATE \"LiteLLM_VerificationToken\" SET blocked = true, expires = now() - interval '1 hour' WHERE token = %s"
    ),
}


@pytest.mark.parametrize(
    ("state", "status"),
    [
        pytest.param("fresh", "active", id="active"),
        pytest.param("blocked", "revoked", id="blocked_is_revoked"),
        pytest.param("expired", "expired", id="past_expiry"),
        pytest.param("blocked_and_expired", "revoked", id="blocked_wins_over_expired"),
    ],
)
def test_key_info_status_is_derived_from_blocked_and_expires(gateway: Gateway, state: str, status: str) -> None:
    """/key/info adds a status field from the live row: "revoked" when blocked (even if also expired), else
    "expired" when expires is in the past, else "active". The row state is forced in the DB so the test does not
    depend on how generate accepts a past expiry; /key/info reads the row directly, not the auth cache."""
    with gateway.scenario() as scenario:
        key: Final = scenario.key()
        if state != "fresh":
            write_rows(_STATE_SQL[state], (digest(key),))  # pyright: ignore[reportArgumentType]  # literal queries above
        info: Final = object_value(gateway.get("/key/info", {"key": key})["info"])
        assert info["status"] == status


