type userNewResponse struct {
	UserID string `json:"user_id"`
	Key    string `json:"key"`
}

type userInfoResponse struct {
	UserID   string                 `json:"user_id"`
	UserInfo map[string]interface{} `json:"user_info"`
}

func resourceLiteLLMUserCreate(d *schema.ResourceData, m interface{}) error {
	client := m.(*Client)

	userData := buildUserData(d)
	if v, ok := d.GetOk("user_id"); ok {
		userData["user_id"] = v.(string)
	}
	userData["auto_create_key"] = d.Get("auto_create_key").(bool)
	userData["send_invite_email"] = d.Get("send_invite_email").(bool)

	log.Printf("[DEBUG] Create user request payload: %+v", userData)

	resp, err := MakeRequest(client, "POST", endpointUserNew, userData)
	if err != nil {
		return fmt.Errorf("error creating user: %w", err)
	}
	defer resp.Body.Close()

	if err := handleResponse(resp, "creating user"); err != nil {
		return err
	}

	var userResp userNewResponse
	if err := json.NewDecoder(resp.Body).Decode(&userResp); err != nil {
		return fmt.Errorf("error decoding create user response: %w", err)
	}
	if userResp.UserID == "" {
		return fmt.Errorf("create user response did not contain a user_id")
	}

	d.SetId(userResp.UserID)
	if userResp.Key != "" {
		d.Set("key", userResp.Key)
	}
	log.Printf("[INFO] User created with ID: %s", userResp.UserID)

	return resourceLiteLLMUserRead(d, m)
}

func resourceLiteLLMUserRead(d *schema.ResourceData, m interface{}) error {
	client := m.(*Client)

	log.Printf("[INFO] Reading user with ID: %s", d.Id())

	resp, err := MakeRequest(client, "GET", fmt.Sprintf("%s?user_id=%s", endpointUserInfo, url.QueryEscape(d.Id())), nil)
	if err != nil {
		return fmt.Errorf("error reading user: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode == http.StatusNotFound {
		log.Printf("[WARN] User with ID %s not found, removing from state", d.Id())
		d.SetId("")
		return nil
	}

	if err := handleResponse(resp, "reading user"); err != nil {
		return err
	}

	var infoResp userInfoResponse
	if err := json.NewDecoder(resp.Body).Decode(&infoResp); err != nil {
		return fmt.Errorf("error decoding user info response: %w", err)
	}
	if infoResp.UserInfo == nil {
		log.Printf("[WARN] User with ID %s has no user_info, removing from state", d.Id())
		d.SetId("")
		return nil
	}

	d.Set("user_id", d.Id())
	setUserStateFromInfo(d, infoResp.UserInfo)

	log.Printf("[INFO] Successfully read user with ID: %s", d.Id())
	return nil
}

func setUserStateFromInfo(d *schema.ResourceData, info map[string]interface{}) {
	for _, key := range []string{"user_email", "user_alias", "user_role", "budget_duration"} {
		if v, ok := info[key].(string); ok && v != "" {
			d.Set(key, v)
		}
	}
	if v, ok := info["max_budget"].(float64); ok {
		d.Set("max_budget", v)
	}
	for _, key := range []string{"tpm_limit", "rpm_limit", "max_parallel_requests"} {
		if v, ok := info[key].(float64); ok {
			d.Set(key, int(v))
		}
	}
	for _, key := range []string{"teams", "models"} {
		if v, ok := info[key].([]interface{}); ok && len(v) > 0 {
			d.Set(key, v)
		}
	}
	if v, ok := info["metadata"].(map[string]interface{}); ok && len(v) > 0 {
		d.Set("metadata", v)
	}
	if v, ok := info["model_max_budget"].(map[string]interface{}); ok && len(v) > 0 {
		if encoded, err := json.Marshal(v); err == nil {
			d.Set("model_max_budget", string(encoded))
		}
	}
}

func resourceLiteLLMUserUpdate(d *schema.ResourceData, m interface{}) error {
	client := m.(*Client)

	userData := buildUserData(d)
	userData["user_id"] = d.Id()

	log.Printf("[DEBUG] Update user request payload: %+v", userData)

	resp, err := MakeRequest(client, "POST", endpointUserUpdate, userData)
	if err != nil {
		return fmt.Errorf("error updating user: %w", err)
	}
	defer resp.Body.Close()

	if err := handleResponse(resp, "updating user"); err != nil {
		return err
	}

	log.Printf("[INFO] Successfully updated user with ID: %s", d.Id())
	return resourceLiteLLMUserRead(d, m)
}

func resourceLiteLLMUserDelete(d *schema.ResourceData, m interface{}) error {
	client := m.(*Client)

	log.Printf("[INFO] Deleting user with ID: %s", d.Id())

	resp, err := MakeRequest(client, "POST", endpointUserDelete, map[string]interface{}{
		"user_ids": []string{d.Id()},
	})
	if err != nil {
		return fmt.Errorf("error deleting user: %w", err)
	}
	defer resp.Body.Close()

	if err := handleResponse(resp, "deleting user"); err != nil {
		return err
	}

	log.Printf("[INFO] Successfully deleted user with ID: %s", d.Id())
	d.SetId("")
	return nil
}

func buildUserData(d *schema.ResourceData) map[string]interface{} {
	userData := map[string]interface{}{
		"blocked": d.Get("blocked").(bool),
	}

	for _, key := range []string{
		"user_email", "user_alias", "user_role", "teams", "models", "max_budget",
		"budget_duration", "tpm_limit", "rpm_limit", "max_parallel_requests",
		"metadata", "key_alias", "aliases", "config", "permissions", "guardrails",
	} {
		if v, ok := d.GetOk(key); ok {
			userData[key] = v
		}
	}

	if v, ok := d.GetOk("model_max_budget"); ok {
		var parsed map[string]interface{}
		if err := json.Unmarshal([]byte(v.(string)), &parsed); err == nil {
			userData["model_max_budget"] = parsed
		}
	}

	return userData
}
