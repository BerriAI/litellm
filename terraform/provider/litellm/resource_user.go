const (
	endpointUserNew    = "/user/new"
	endpointUserInfo   = "/user/info"
	endpointUserUpdate = "/user/update"
	endpointUserDelete = "/user/delete"
)

func userSuppressEquivalentJSON(k, oldValue, newValue string, d *schema.ResourceData) bool {
	var oldParsed, newParsed interface{}
	if err := json.Unmarshal([]byte(oldValue), &oldParsed); err != nil {
		return false
	}
	if err := json.Unmarshal([]byte(newValue), &newParsed); err != nil {
		return false
	}
	return reflect.DeepEqual(oldParsed, newParsed)
}

