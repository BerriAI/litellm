"""
1000 evaluation prompts designed to reveal Thompson Sampling bandit advantage
over static tier-based routing.

Key design principle: the keyword-based classifier's tier assignments DON'T
perfectly predict which model (4B vs 9B) will succeed. This creates room for
the bandit to learn better per-tier distributions than static routing provides.

Structure:
  - SIMPLE tier prompts (classified SIMPLE by keyword/length heuristics):
    - 70% genuinely trivial (4B handles fine) -> static SIMPLE->4B is correct
    - 30% "deceptively simple" (short/simple keywords but actually hard for 4B)
      -> static loses here; bandit learns to shift toward 9B

  - MEDIUM tier prompts (classified MEDIUM due to code/technical keywords):
    - 50% truly need 9B (complex logic despite moderate classification)
    - 50% "easy mediums" (trigger keywords but actually trivial for 4B)
      -> static wastes latency sending all MEDIUM->9B; bandit learns 4B is fine

Two categories: math/logic (500) and code (500).
Within each, prompts are tagged with expected difficulty (1-5) independent
of how the classifier routes them.
"""

