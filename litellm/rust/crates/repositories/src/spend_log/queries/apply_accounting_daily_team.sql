SELECT id, team_id, date, api_key, model, custom_llm_provider, mcp_namespaced_tool_name, endpoint, model_group, prompt_tokens, completion_tokens, api_requests, successful_requests, failed_requests, cache_read_input_tokens, cache_creation_input_tokens, compression_saved_tokens, total_response_time_ms, timed_requests, spend, compression_savings_spend, prompt_caching_savings_spend, gateway_injected_caching_savings_spend, autorouter_savings_spend, guardrail_spend, customer_margin_spend, (NOW() AT TIME ZONE 'UTC')
FROM jsonb_to_recordset($1::jsonb) AS input(
    id text,
    team_id text,
    date text,
    api_key text,
    model text,
    custom_llm_provider text,
    mcp_namespaced_tool_name text,
    endpoint text,
    model_group text,
    prompt_tokens bigint,
    completion_tokens bigint,
    api_requests bigint,
    successful_requests bigint,
    failed_requests bigint,
    cache_read_input_tokens bigint,
    cache_creation_input_tokens bigint,
    compression_saved_tokens bigint,
    total_response_time_ms bigint,
    timed_requests bigint,
    spend double precision,
    compression_savings_spend double precision,
    prompt_caching_savings_spend double precision,
    gateway_injected_caching_savings_spend double precision,
    autorouter_savings_spend double precision,
    guardrail_spend double precision,
    customer_margin_spend double precision
)
ORDER BY team_id COLLATE "C", date COLLATE "C", api_key COLLATE "C", model COLLATE "C", custom_llm_provider COLLATE "C", mcp_namespaced_tool_name COLLATE "C", endpoint COLLATE "C"
ON CONFLICT (team_id, date, api_key, model, custom_llm_provider, mcp_namespaced_tool_name, endpoint) DO UPDATE SET
    prompt_tokens = stored.prompt_tokens + EXCLUDED.prompt_tokens,
    completion_tokens = stored.completion_tokens + EXCLUDED.completion_tokens,
    api_requests = stored.api_requests + EXCLUDED.api_requests,
    successful_requests = stored.successful_requests + EXCLUDED.successful_requests,
    failed_requests = stored.failed_requests + EXCLUDED.failed_requests,
    cache_read_input_tokens = stored.cache_read_input_tokens + EXCLUDED.cache_read_input_tokens,
    cache_creation_input_tokens = stored.cache_creation_input_tokens + EXCLUDED.cache_creation_input_tokens,
    compression_saved_tokens = stored.compression_saved_tokens + EXCLUDED.compression_saved_tokens,
    total_response_time_ms = stored.total_response_time_ms + EXCLUDED.total_response_time_ms,
    timed_requests = stored.timed_requests + EXCLUDED.timed_requests,
    spend = stored.spend + EXCLUDED.spend,
    compression_savings_spend = stored.compression_savings_spend + EXCLUDED.compression_savings_spend,
    prompt_caching_savings_spend = stored.prompt_caching_savings_spend + EXCLUDED.prompt_caching_savings_spend,
