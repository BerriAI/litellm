class _CompletionDispatchContext:
    _azure_detection_model: str
    acompletion: bool
    api_base: str | None
    api_key: str | None
    api_version: str | None
    client: Any
    custom_llm_provider: str
    custom_prompt_dict: dict
    extra_headers: dict | None
    headers: dict
    hf_model_name: str | None
    kwargs: dict
    litellm_params: dict
    logger_fn: Callable | None
    logging: LiteLLMLoggingObj
    max_retries: int | None
    max_tokens: int | None
    messages: list
    metadata: dict | None
    model: str
    model_response: ModelResponse
    optional_params: dict
    organization: str | None
    provider_config: BaseConfig | None
    shared_session: ClientSession | None
    stream: bool | None
    temperature: float | None
    text_completion: bool
    timeout: float | str | httpx.Timeout | None
    top_p: float | None


_CompletionDispatchResult = Union[
    Coroutine[Any, Any, Union["ModelResponse", "CustomStreamWrapper"]],
    "ModelResponse",
    "CustomStreamWrapper",
]
