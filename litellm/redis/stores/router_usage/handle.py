from __future__ import annotations

from collections.abc import Awaitable, Mapping, Sequence
from typing import Protocol

from litellm.caching.redis_batch import NativePending
from litellm.redis.stores.router_usage.types import CounterIncrement, UsageCounter
from litellm.rust_bridge._native import NativeRedisClient, NativeRequestRedis, NativeSend


class DeclaredUsage(Protocol):
    """A usage read declared on a batch, with the throttle refreshes it reserved."""

    @property
    def read(self) -> NativePending[Sequence[float | None]]: ...
    def release(self) -> None: ...


class RouterUsageHandle(Protocol):
    @property
    def has_redis(self) -> bool: ...
    def attach(self, client: NativeRedisClient, /) -> bool: ...
    def increment(self, counter: UsageCounter, value: float, ttl_seconds: int) -> Awaitable[float | None]: ...
    def increment_deployment(
        self,
        deployment_id: str,
        model: str | None,
        minute: str,
        tokens: float,
        requests: int,
    ) -> Awaitable[None]: ...
    def get_many(self, counters: Sequence[UsageCounter]) -> Awaitable[Sequence[float | None]]: ...
    def increment_sync(self, counter: UsageCounter, value: float, ttl_seconds: int) -> float | None: ...
    def increment_deployment_sync(
        self,
        deployment_id: str,
        model: str | None,
        minute: str,
        tokens: float,
        requests: int,
    ) -> None: ...
    def get_many_sync(self, counters: Sequence[UsageCounter]) -> Sequence[float | None]: ...
    def usage(self, counters: Sequence[UsageCounter], send: NativeSend) -> DeclaredUsage: ...
    def increment_pipeline(self, increments: Sequence[CounterIncrement]) -> Awaitable[Sequence[float] | None]: ...
    def increment_post_call(self, request: NativeRequestRedis, increments: Sequence[CounterIncrement]) -> None: ...
    def increment_remote(self, increments: Sequence[CounterIncrement]) -> Awaitable[Sequence[float] | None]: ...
    def increment_local(self, increment: CounterIncrement) -> float: ...
    def get_local(self, counter: UsageCounter) -> float | None: ...
    def get_local_many(self, counters: Sequence[UsageCounter]) -> Sequence[float | None]: ...
    def set_local(self, counter: UsageCounter, value: float) -> None: ...
    def current(self, counter: UsageCounter, limit: float) -> Awaitable[float | None]: ...
    def current_sync(self, counter: UsageCounter, limit: float) -> float | None: ...
    def shared_or_local(self, counter: UsageCounter) -> Awaitable[float | None]: ...
    def flush_local_counters(self) -> None: ...
    def snapshot(self) -> Mapping[str, float]: ...
