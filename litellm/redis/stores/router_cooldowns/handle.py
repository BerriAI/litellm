from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from typing import Protocol, TypeAlias

from litellm.caching.redis_batch import NativePending
from litellm.redis.stores.router_cooldowns.types import ActiveCooldowns, CooldownCacheValue
from litellm.rust_bridge._native import NativeRedisClient, NativeSend


class RouterCooldownsHandle(Protocol):
    def attach(self, client: NativeRedisClient, redis_ttl_seconds: int = 60, /) -> bool: ...
    def put(self, model_id: str, cooldown: Mapping[str, object], ttl_seconds: float) -> None: ...
    def increment_allowed_fails(self, model_id: str, suffix: str | None, ttl_seconds: float) -> int: ...
    def active(self, model_ids: Sequence[str], send: NativeSend) -> NativePending[ActiveCooldowns]: ...
    def active_sync(self, model_ids: Sequence[str]) -> Sequence[tuple[str, CooldownCacheValue]]: ...
    def minimum(self, model_ids: Sequence[str]) -> float | None: ...
    def delete_local(self, model_id: str) -> None: ...
    def flush_local_counters(self) -> None: ...
    def snapshot(self) -> Mapping[str, CooldownCacheValue]: ...


HandleFactory: TypeAlias = Callable[[NativeRedisClient | None], RouterCooldownsHandle]
