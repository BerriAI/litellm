from __future__ import annotations

from collections.abc import Awaitable, Callable, Sequence
from typing import Protocol, TypeAlias

from litellm.caching.redis_batch import NativePending
from litellm.redis.stores.rate_limits.types import (
    LocalValue,
    NativeAtomicCounter,
    NativeCounter,
    NativeEntry,
    NativeIncrement,
    NativeOverLimit,
    NativeScope,
)
from litellm.rust_bridge._native import NativeRedisClient, NativeRequestRedis, NativeSend


class RateLimitsHandle(Protocol):
    @property
    def has_redis(self) -> bool: ...
    def slot_groups(self, scopes: Sequence[NativeScope], force: bool) -> list[list[int]]: ...
    def get_local(self, entry: NativeEntry) -> LocalValue | None: ...
    def set_local(self, entry: NativeEntry, value: LocalValue, ttl_seconds: float | None) -> None: ...
    def get(self, entry: NativeEntry, *, backfill_ttl_seconds: float | None = None) -> Awaitable[LocalValue | None]: ...
    def sliding_window(
        self, counters: Sequence[NativeCounter], now: int, window_size: int, send: NativeSend
    ) -> NativePending[list[tuple[str, int]]] | None: ...
    def read_counters(self, counters: Sequence[NativeCounter], send: NativeSend) -> NativePending[list[str | None]] | None: ...
    def check_and_increment(
        self, counters: Sequence[NativeAtomicCounter], send: NativeSend
    ) -> NativePending[tuple[NativeOverLimit | None, list[tuple[int, int]]]] | None: ...
    def guarded_increment(
        self, counter: NativeCounter, expected_window_start: str, amount: float, ttl_seconds: int | None, send: NativeSend
    ) -> NativePending[tuple[bool, int]] | None: ...
    def parallel_acquire(
        self, gauges: Sequence[tuple[NativeScope, int]], slot_ttl_seconds: int, slot_id: str, send: NativeSend
    ) -> NativePending[tuple[NativeOverLimit | None, list[int]]] | None: ...
    def parallel_release(
        self, gauges: Sequence[NativeScope], slot_id: str, send: NativeSend
    ) -> NativePending[list[int]] | None: ...
    def parallel_count(
        self, gauges: Sequence[NativeScope], slot_ttl_seconds: int, send: NativeSend
    ) -> NativePending[list[int]] | None: ...
    def token_increment(
        self, increments: Sequence[NativeIncrement], send: NativeSend
    ) -> NativePending[list[float]] | None: ...
    def token_increment_post_call(self, request: NativeRequestRedis, increments: Sequence[NativeIncrement]) -> bool: ...
    def parallel_release_post_call(
        self, request: NativeRequestRedis, gauges: Sequence[NativeScope], slot_id: str
    ) -> bool: ...
    def increment(self, increment: NativeIncrement) -> Awaitable[int | float]: ...
    def increment_many(self, increments: Sequence[NativeIncrement]) -> Awaitable[None]: ...
    def increment_many_post_call(self, request: NativeRequestRedis, increments: Sequence[NativeIncrement]) -> None: ...


HandleFactory: TypeAlias = Callable[[NativeRedisClient | None, float | None, int], RateLimitsHandle]
