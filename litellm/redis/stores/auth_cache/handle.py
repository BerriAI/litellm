from __future__ import annotations

from collections.abc import Awaitable, Sequence
from typing import Protocol

from litellm.caching.redis_batch import NativePending
from litellm.redis.stores.auth_cache.types import WriteBack
from litellm.rust_bridge._native import AuthObject, LocalSizes, NativeRedisClient, NativeRequestRedis, NativeSend


class TeamRoster(Protocol):
    def member(self, user_id: str) -> object: ...


class AuthCacheHandle(Protocol):
    def attach(self, client: NativeRedisClient) -> bool: ...
    @property
    def has_redis(self) -> bool: ...
    def get(self, key: AuthObject, request: NativeRequestRedis | None) -> Awaitable[object]: ...
    def get_sync(self, key: AuthObject) -> object: ...
    def set(
        self, key: AuthObject, value: object, ttl_seconds: float | None, request: NativeRequestRedis | None
    ) -> Awaitable[None]: ...
    def set_sync(
        self, key: AuthObject, value: object, ttl_seconds: float | None, request: NativeRequestRedis | None
    ) -> None: ...
    def lease(self, key: AuthObject) -> Awaitable[str | None]: ...
    def set_leased(
        self,
        key: AuthObject,
        lease: str | None,
        value: object,
        ttl_seconds: float | None,
        request: NativeRequestRedis | None,
    ) -> Awaitable[bool]: ...
    def declare_set(
        self, key: AuthObject, value: object, ttl_seconds: float | None, send: NativeSend
    ) -> NativePending[None]: ...
    def declare_delete(self, key: str, send: NativeSend) -> NativePending[None]: ...
    def set_many(
        self,
        entries: Sequence[tuple[AuthObject, object]],
        ttl_seconds: float | None,
        request: NativeRequestRedis | None,
    ) -> Awaitable[None]: ...
    def write_back(self, entries: Sequence[WriteBack], send: NativeSend) -> Awaitable[None]: ...
    def delete(self, keys: Sequence[str]) -> Awaitable[None]: ...
    def delete_sync(self, keys: Sequence[str]) -> None: ...
    def get_many(self, keys: Sequence[AuthObject], send: NativeSend) -> NativePending[Sequence[object]] | None: ...
    def increment_if_present(self, key: AuthObject, amount: float) -> Awaitable[float | None]: ...
    def get_local(self, key: AuthObject) -> object: ...
    def team_snapshot(
        self, key: AuthObject, request: NativeRequestRedis | None
    ) -> Awaitable[tuple[object, TeamRoster | None] | None]: ...
    def team_fields(
        self,
        key: AuthObject,
        fields: Sequence[str] | None,
        user_id: str | None,
        request: NativeRequestRedis | None,
    ) -> Awaitable[object]: ...
    def local_team_fields(self, key: AuthObject, fields: Sequence[str] | None, user_id: str | None) -> object: ...
    def add_local_team_spend(self, key: AuthObject, delta: float) -> bool: ...
    def get_local_by_key(self, key: str) -> object: ...
    def set_local(self, key: AuthObject, value: object, ttl_seconds: float | None = None) -> None: ...
    def local_generation(self, key: AuthObject) -> int: ...
    def set_local_if_current(
        self, generation: int, key: AuthObject, value: object, ttl_seconds: float | None
    ) -> bool: ...
    def delete_local(self, key: str) -> None: ...
    def flush_local(self) -> None: ...
    def len_local(self) -> LocalSizes: ...
    def reconfigure(self, *, memory_entries: int, memory_ttl_seconds: float | None = None) -> None: ...
