from __future__ import annotations

from collections.abc import Awaitable, Sequence
from typing import Protocol

from litellm.caching.redis_batch import NativePending
from litellm.redis.stores.auth_cache.types import WriteBack
from litellm.rust_bridge._native import LocalSizes, NativeSend


class AuthCacheHandle(Protocol):
    def get(self, key: str) -> Awaitable[object]: ...
    def get_sync(self, key: str) -> object: ...
    def set(self, key: str, value: object, ttl_seconds: float | None = None) -> Awaitable[None]: ...
    def set_sync(self, key: str, value: object, ttl_seconds: float | None = None) -> None: ...
    def lease(self, key: str) -> Awaitable[str | None]: ...
    def set_leased(
        self, key: str, lease: str | None, value: object, ttl_seconds: float | None = None
    ) -> Awaitable[bool]: ...
    def declare_set(
        self, key: str, value: object, ttl_seconds: float | None, send: NativeSend
    ) -> NativePending[None]: ...
    def declare_delete(self, key: str, send: NativeSend) -> NativePending[None]: ...
    def set_many(self, entries: Sequence[tuple[str, object]], ttl_seconds: float | None = None) -> Awaitable[None]: ...
    def write_back(self, entries: Sequence[WriteBack], send: NativeSend) -> Awaitable[None]: ...
    def delete(self, keys: Sequence[str]) -> Awaitable[None]: ...
    def delete_sync(self, keys: Sequence[str]) -> None: ...
    def get_many(self, keys: Sequence[str], send: NativeSend) -> NativePending[Sequence[object]] | None: ...
    def increment_if_present(self, key: str, amount: float) -> Awaitable[float | None]: ...
    def get_local(self, key: str) -> object: ...
    def local_ttl(self, key: str) -> float | None: ...
    def set_local(self, key: str, value: object, ttl_seconds: float | None = None) -> None: ...
    def delete_local(self, key: str) -> None: ...
    def flush_local(self) -> None: ...
    def len_local(self) -> LocalSizes: ...
    def reconfigure(self, *, memory_entries: int, memory_ttl_seconds: float | None = None) -> None: ...
