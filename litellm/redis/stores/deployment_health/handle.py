from __future__ import annotations

from collections.abc import Awaitable
from typing import Protocol

from litellm.redis.stores.deployment_health.types import DeploymentHealthStates
from litellm.rust_bridge._native import NativeRedisClient


class DeploymentHealthHandle(Protocol):
    @property
    def has_redis(self) -> bool: ...
    def attach(self, client: NativeRedisClient) -> bool: ...
    def get(self) -> Awaitable[DeploymentHealthStates | None]: ...
    def get_sync(self) -> DeploymentHealthStates | None: ...
    def get_shared_sync(self) -> DeploymentHealthStates | None: ...
    def set_sync(self, states: DeploymentHealthStates, ttl_seconds: float) -> None: ...
