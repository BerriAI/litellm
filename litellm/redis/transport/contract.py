import math
from collections.abc import Awaitable, Callable, Generator, Mapping, Sequence
from dataclasses import dataclass
from datetime import timedelta
from typing import Final, Literal, Protocol, TypeAlias, TypeVar

Arg: TypeAlias = str | bytes | int | float
EvalReply: TypeAlias = int | bytes | None | tuple["EvalReply", ...]
InfoScalar: TypeAlias = str | int | float
InfoValue: TypeAlias = InfoScalar | Mapping[str, InfoScalar]
Popped: TypeAlias = bytes | tuple[bytes, ...] | None

_T: Final = TypeVar("_T")
_T_co: Final = TypeVar("_T_co", covariant=True)


class Admit(Protocol):
    def __call__(self, call: Callable[[], Awaitable[_T]], /) -> Awaitable[_T]: ...


@dataclass(frozen=True, slots=True)
class RedisFailure:
    kind: Literal["transport", "server", "decode", "breaker_open"]
    message: str
    timeout: bool = False


@dataclass(frozen=True, slots=True)
class PubSubMessage:
    channel: bytes
    data: bytes


def ttl_ms(ttl: timedelta) -> int:
    return max(1, math.ceil(ttl / timedelta(milliseconds=1)))


class BatchReply(Protocol[_T_co]):
    def __await__(self) -> Generator[object, None, _T_co]: ...

    @property
    def done(self) -> bool: ...


class RedisCommandBatch(Protocol):
    def get(self, key: str) -> BatchReply[bytes | None | RedisFailure]: ...

    def mget(self, keys: Sequence[str]) -> BatchReply[tuple[bytes | None, ...] | RedisFailure]: ...

    def set(
        self, key: str, value: Arg, *, ttl: timedelta | None, nx: bool = False
    ) -> BatchReply[bool | RedisFailure]: ...

    def delete(self, *keys: str) -> BatchReply[int | RedisFailure]: ...

    def set_seconds(
        self, key: str, value: Arg, *, ttl: timedelta | None, nx: bool = False
    ) -> BatchReply[bool | RedisFailure]: ...

    def incrby(self, key: str, amount: int) -> BatchReply[int | RedisFailure]: ...

    def incrbyfloat(self, key: str, amount: float) -> BatchReply[float | RedisFailure]: ...

    def expire(self, key: str, ttl: timedelta) -> BatchReply[bool | RedisFailure]: ...

    def expire_seconds(self, key: str, ttl: timedelta) -> BatchReply[bool | RedisFailure]: ...

    def ttl(self, key: str) -> BatchReply[int | RedisFailure]: ...

    def rpush(self, key: str, *values: Arg) -> BatchReply[int | RedisFailure]: ...

    def lpop(self, key: str, count: int | None = None) -> BatchReply[Popped | RedisFailure]: ...

    def ltrim(self, key: str, start: int, stop: int) -> BatchReply[bool | RedisFailure]: ...

    def sadd(self, key: str, *members: Arg) -> BatchReply[int | RedisFailure]: ...

    def eval(self, script: str, keys: Sequence[str], args: Sequence[Arg]) -> BatchReply[EvalReply | RedisFailure]: ...

    async def flush(self) -> None: ...


class RedisSubscription(Protocol):
    async def get_message(self, *, timeout: float) -> PubSubMessage | None | RedisFailure: ...

    async def close(self) -> None | RedisFailure: ...


class RedisTransport(Protocol):
    async def get(self, key: str) -> bytes | None | RedisFailure: ...

    async def mget(self, keys: Sequence[str]) -> tuple[bytes | None, ...] | RedisFailure: ...

    async def set(self, key: str, value: Arg, *, ttl: timedelta | None, nx: bool = False) -> bool | RedisFailure: ...

    async def delete(self, *keys: str) -> int | RedisFailure: ...

    async def set_seconds(
        self, key: str, value: Arg, *, ttl: timedelta | None, nx: bool = False
    ) -> bool | RedisFailure: ...

    async def incrby(self, key: str, amount: int) -> int | RedisFailure: ...

    async def incrbyfloat(self, key: str, amount: float) -> float | RedisFailure: ...

    async def expire(self, key: str, ttl: timedelta) -> bool | RedisFailure: ...

    async def expire_seconds(self, key: str, ttl: timedelta) -> bool | RedisFailure: ...

    async def ttl(self, key: str) -> int | RedisFailure: ...

    async def rpush(self, key: str, *values: Arg) -> int | RedisFailure: ...

    async def lpop(self, key: str, count: int | None = None) -> Popped | RedisFailure: ...

    async def ltrim(self, key: str, start: int, stop: int) -> bool | RedisFailure: ...

    async def sadd(self, key: str, *members: Arg) -> int | RedisFailure: ...

    async def scan(self, prefix: str, *, limit: int) -> tuple[bytes, ...] | RedisFailure: ...

    async def eval(self, script: str, keys: Sequence[str], args: Sequence[Arg]) -> EvalReply | RedisFailure: ...

    def batch(self, *, transaction: bool = False) -> RedisCommandBatch: ...

    def request_batch(self) -> RedisCommandBatch | None: ...

    def post_call_batch(self) -> RedisCommandBatch | None: ...

    async def publish(self, channel: str, message: str | bytes) -> int | RedisFailure: ...

    async def publish_all(self, channel: str, messages: Sequence[str | bytes]) -> tuple[int, ...] | RedisFailure: ...

    async def subscribe(self, *channels: str) -> RedisSubscription | RedisFailure: ...

    async def ping(self) -> bool | RedisFailure: ...

    async def info(self) -> Mapping[str, InfoValue] | RedisFailure: ...

    async def client_list(self) -> tuple[Mapping[str, str], ...] | RedisFailure: ...

    async def flushall(self) -> bool | RedisFailure: ...
