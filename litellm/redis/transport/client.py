from collections.abc import AsyncIterator, Awaitable, Sequence
from contextlib import AbstractAsyncContextManager
from datetime import timedelta
from typing import Protocol

from litellm.redis.transport.contract import Arg


class RedisPipeline(Protocol):
    def get(self, name: str) -> object: ...
    def mget(self, keys: Sequence[str]) -> object: ...
    def set(
        self, name: str, value: Arg, ex: timedelta | None = None, px: int | None = None, nx: bool = False
    ) -> object: ...
    def delete(self, *names: str) -> object: ...
    def incrby(self, name: str, amount: int) -> object: ...
    def incrbyfloat(self, name: str, amount: float) -> object: ...
    def expire(self, name: str, time: timedelta) -> object: ...
    def pexpire(self, name: str, time: int) -> object: ...
    def ttl(self, name: str) -> object: ...
    def rpush(self, name: str, *values: Arg) -> object: ...
    def lpop(self, name: str, count: int | None = None) -> object: ...
    def ltrim(self, name: str, start: int, end: int) -> object: ...
    def sadd(self, name: str, *values: Arg) -> object: ...
    def eval(self, script: str, numkeys: int, *keys_and_args: Arg) -> object: ...
    def evalsha(self, sha: str, numkeys: int, *keys_and_args: Arg) -> object: ...
    def publish(self, channel: str, message: str | bytes) -> object: ...
    async def execute(self, raise_on_error: bool = True) -> list[object]: ...


class PipelineClient(Protocol):
    def pipeline(self, transaction: bool = True) -> AbstractAsyncContextManager[RedisPipeline]: ...


class AsyncRedisCommands(Protocol):
    def get(self, name: str) -> Awaitable[object]: ...

    def mget(self, keys: Sequence[str]) -> Awaitable[object]: ...

    def set(
        self, name: str, value: Arg, *, nx: bool, px: int | None = None, ex: timedelta | None = None
    ) -> Awaitable[object]: ...

    def delete(self, *names: str) -> Awaitable[object]: ...

    def incrby(self, name: str, amount: int) -> Awaitable[object]: ...

    def incrbyfloat(self, name: str, amount: float) -> Awaitable[object]: ...

    def pexpire(self, name: str, time: int) -> Awaitable[object]: ...

    def expire(self, name: str, time: int) -> Awaitable[object]: ...

    def ttl(self, name: str) -> Awaitable[object]: ...

    def rpush(self, name: str, *values: Arg) -> Awaitable[object]: ...

    def lpop(self, name: str, count: int | None = None) -> Awaitable[object]: ...

    def ltrim(self, name: str, start: int, end: int) -> Awaitable[object]: ...

    def sadd(self, name: str, *values: Arg) -> Awaitable[object]: ...

    def scan_iter(self, *, match: str, count: int) -> AsyncIterator[object]: ...

    def eval(self, script: str, numkeys: int, *keys_and_args: Arg) -> Awaitable[object]: ...

    def evalsha(self, sha: str, numkeys: int, *keys_and_args: Arg) -> Awaitable[object]: ...

    def pipeline(self, transaction: bool = True) -> AbstractAsyncContextManager[RedisPipeline]: ...

    def ping(self) -> Awaitable[object]: ...

    def info(self) -> Awaitable[object]: ...

    def client_list(self) -> Awaitable[object]: ...

    def flushall(self) -> Awaitable[object]: ...


class AsyncPubSub(Protocol):
    def subscribe(self, *channels: str) -> Awaitable[object]: ...

    def get_message(self, *, ignore_subscribe_messages: bool, timeout: float) -> Awaitable[object]: ...

    def reset(self) -> Awaitable[object]: ...


class AsyncPubSubClient(Protocol):
    def publish(self, channel: str, message: str | bytes) -> Awaitable[object]: ...

    def pubsub(self) -> AsyncPubSub: ...

    def pipeline(self, transaction: bool = True) -> AbstractAsyncContextManager[RedisPipeline]: ...
