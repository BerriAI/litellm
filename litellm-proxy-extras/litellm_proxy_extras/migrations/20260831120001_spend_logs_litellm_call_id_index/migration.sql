-- CreateIndex
--
-- PostgreSQL rejects CREATE INDEX CONCURRENTLY on partitioned tables
-- (SQLSTATE 0A000: "cannot create index on partitioned table ... concurrently").
-- Operators who ran db_scripts/partition_spend_logs.sql therefore fail this
-- migration under `prisma migrate deploy` (Prisma P3018), blocking later ones.
--
-- A plain CREATE INDEX on the partitioned parent is supported and propagates to
-- every current and future partition (same pattern as partition_spend_logs.sql).
-- Non-partitioned deployments keep the same index name and columns; the build
-- takes a brief stronger lock than CONCURRENTLY would have.
--
-- Do not edit this file after it has been applied to any database: Prisma
-- checksums migrations; add a new migration instead.
CREATE INDEX IF NOT EXISTS "LiteLLM_SpendLogs_litellm_call_id_idx" ON "LiteLLM_SpendLogs"("litellm_call_id");
